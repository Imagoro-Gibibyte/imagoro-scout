#!/usr/bin/env python3
"""Render Ollama Modelfiles for every role in roles.toml.

Each Scout model is a thin layer over shared Qwen3 weights: a system prompt, a temperature,
a context size, and (for every role except the managers) reasoning switched off. Building
them is cheap, so prompts are versioned and every tag carries the prompt version.

  python models/render.py --prompts models/prompts.example --out build/modelfiles
  ollama create scout-sec-alert1.3.0 -f build/modelfiles/scout-sec-alert1.3.0.Modelfile

The deployed prompts are not in this repo (they describe what the detectors look for);
`prompts.example/` holds short stand-ins with the same shape. A missing prompt is an error.

Why `/no_think` in SYSTEM is not enough: harnesses such as CrewAI send their own system
message, which replaces the Modelfile's. Clients must also ask for no reasoning per request
(`reasoning_effort: "none"` on Ollama's OpenAI endpoint); see docs/models.md.
"""
from __future__ import annotations

import argparse
import sys
import tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parent


def load(path: Path = HERE / "roles.toml") -> dict:
    with path.open("rb") as f:
        return tomllib.load(f)


def roles(cfg: dict) -> list[tuple[str, str, dict]]:
    out = []
    for suite in ("security", "nav"):
        for name, r in cfg.get(suite, {}).items():
            out.append((suite, name, r))
    return out


def tag(cfg: dict, suite: str, r: dict) -> str:
    # Security tags carry the prompt version; nav tags already embed their own version.
    return f"{r['tag']}{cfg['meta']['prompt_version']}" if suite == "security" else r["tag"]


def modelfile(cfg: dict, suite: str, name: str, r: dict, prompt: str) -> str:
    system = prompt.strip().replace('"""', "'''")
    if not r["thinking"] and not system.rstrip().endswith("/no_think"):
        system += "\n/no_think"
    return "\n".join([
        f"# {tag(cfg, suite, r)} ({suite}/{name}), generated by models/render.py; do not edit",
        f"FROM {r['base']}",
        f'SYSTEM """{system}"""',
        f"PARAMETER temperature {r['temp']}",
        f"PARAMETER num_ctx {cfg['meta']['num_ctx']}",
        "",
    ])


def validate(cfg: dict) -> None:
    seen = {}
    for suite, name, r in roles(cfg):
        for k in ("tag", "base", "temp", "thinking", "tier"):
            if k not in r:
                raise ValueError(f"{suite}.{name}: missing {k}")
        if not r["thinking"] and r["temp"] > 0.2:
            raise ValueError(f"{suite}.{name}: contract roles stay at temperature <= 0.2")
        if r["tier"] not in ("heavy", "light", "edge"):
            raise ValueError(f"{suite}.{name}: unknown tier {r['tier']}")
        t = tag(cfg, suite, r)
        if t in seen and seen[t] != (r["base"], r["temp"]):
            raise ValueError(f"{t} assigned twice with different settings ({seen[t]} vs {(r['base'], r['temp'])})")
        seen[t] = (r["base"], r["temp"])
        if "abliterated" in r["base"].lower():
            raise ValueError(f"{suite}.{name}: abliterated bases are not allowed")


def render(cfg: dict, prompts: Path, out: Path) -> list[Path]:
    validate(cfg)
    out.mkdir(parents=True, exist_ok=True)
    written = []
    for suite, name, r in roles(cfg):
        p = prompts / suite / f"{name}.txt"
        if not p.exists():
            raise FileNotFoundError(f"no prompt for {suite}/{name}: {p}")
        f = out / f"{tag(cfg, suite, r)}.Modelfile"
        f.write_text(modelfile(cfg, suite, name, r, p.read_text(encoding="utf-8")), encoding="utf-8")
        written.append(f)
    return written


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--roles", type=Path, default=HERE / "roles.toml")
    ap.add_argument("--prompts", type=Path, default=HERE / "prompts.example")
    ap.add_argument("--out", type=Path, default=Path("build/modelfiles"))
    a = ap.parse_args(argv)
    for f in render(load(a.roles), a.prompts, a.out):
        print(f)
    return 0


if __name__ == "__main__":
    sys.exit(main())
